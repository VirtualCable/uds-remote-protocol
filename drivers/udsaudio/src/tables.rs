// --- pin helpers ----------------------------------------------------------------

const fn ks_pin(
    ranges: &'static [pc::PKSDATARANGE],
    data_flow: i32,
    communication: i32,
    category: &'static pc::GUID,
) -> pc::KSPIN_DESCRIPTOR {
    pc::KSPIN_DESCRIPTOR {
        InterfacesCount: 0,
        Interfaces: ptr::null(),
        MediumsCount: 0,
        Mediums: ptr::null(),
        DataRangesCount: ranges.len() as u32,
        DataRanges: ranges.as_ptr(),
        DataFlow: data_flow,
        Communication: communication,
        Category: category,
        Name: ptr::null(),
        __bindgen_anon_1: pc::KSPIN_DESCRIPTOR__bindgen_ty_1 { Reserved: 0 },
    }
}

const fn pc_pin(ks_descriptor: pc::KSPIN_DESCRIPTOR, max_instances: u32) -> pc::PCPIN_DESCRIPTOR {
    pc::PCPIN_DESCRIPTOR {
        MaxGlobalInstanceCount: max_instances,
        MaxFilterInstanceCount: max_instances,
        MinFilterInstanceCount: 0,
        AutomationTable: ptr::null(),
        KsPinDescriptor: ks_descriptor,
    }
}

